/**
 * Staging: apply receipt_deliveries.method + terminal_printer_configs.connection_type
 * check-constraint widening (EMAIL, BUILTIN).
 *   npx tsx scripts/apply-receipt-email-and-builtin-printer-staging.ts
 */
import { config } from 'dotenv'
import {
  STAGING_PROJECT_REF,
  runSafeSupabaseLinked,
  runShellCommand,
} from './lib/safe-supabase-linked'

config({ path: '.env.test', override: true })

const MIGRATION = 'supabase/migrations/20260718100000_receipt_email_and_builtin_printer.sql'

const url = process.env.SUPABASE_URL!
if (!url?.includes(STAGING_PROJECT_REF)) {
  throw new Error('Refusing: not staging Supabase (.env.test)')
}

function main(): void {
  runShellCommand(`npx supabase link --project-ref ${STAGING_PROJECT_REF}`)
  runSafeSupabaseLinked(STAGING_PROJECT_REF, ['db', 'query', '--linked', '-f', MIGRATION])
  runSafeSupabaseLinked(STAGING_PROJECT_REF, [
    'migration',
    'repair',
    '--linked',
    '--status',
    'applied',
    '20260718100000',
  ])
  console.log('RECEIPT_EMAIL_AND_BUILTIN_PRINTER_STAGING_OK')
}

main()
